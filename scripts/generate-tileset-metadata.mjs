#!/usr/bin/env node
import fs from 'node:fs'
import path from 'node:path'

const BORDER_KEYS = ['topLeft', 'top', 'topRight', 'left', 'right', 'bottomLeft', 'bottom', 'bottomRight']

function parseArgs(argv) {
  const options = {
    image: 'assets/map.png',
    output: 'assets/map.generated.json',
    name: 'generated-tileset',
    textureKey: 'tilesheet',
    tileWidth: 32,
    tileHeight: 32,
    margin: 0,
    spacing: 0,
    columns: undefined,
    rows: undefined,
  }

  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i]
    if (!arg.startsWith('--')) continue

    const key = arg.slice(2)
    const value = argv[i + 1]
    if (value == null || value.startsWith('--')) {
      throw new Error(`Missing value for --${key}`)
    }

    i += 1
    switch (key) {
      case 'image':
      case 'output':
      case 'name':
      case 'textureKey':
        options[key] = value
        break
      case 'tileWidth':
      case 'tileHeight':
      case 'margin':
      case 'spacing':
      case 'columns':
      case 'rows':
        options[key] = Number.parseInt(value, 10)
        if (!Number.isInteger(options[key]) || options[key] < 0) {
          throw new Error(`Invalid numeric value for --${key}: ${value}`)
        }
        break
      default:
        throw new Error(`Unknown option: --${key}`)
    }
  }

  if (options.tileWidth <= 0 || options.tileHeight <= 0) {
    throw new Error('tileWidth and tileHeight must be positive integers')
  }

  return options
}

function readPngDimensions(filePath) {
  const buffer = fs.readFileSync(filePath)
  const pngSignature = '89504e470d0a1a0a'
  if (buffer.subarray(0, 8).toString('hex') !== pngSignature) {
    throw new Error(`Only PNG files are supported right now: ${filePath}`)
  }

  const ihdr = buffer.subarray(12, 16).toString('ascii')
  if (ihdr !== 'IHDR') {
    throw new Error(`PNG header is invalid in ${filePath}`)
  }

  return {
    width: buffer.readUInt32BE(16),
    height: buffer.readUInt32BE(20),
  }
}

function deriveGrid({ width, height, tileWidth, tileHeight, margin, spacing, columns, rows }) {
  const derivedColumns = columns ?? solveAxis(width, tileWidth, margin, spacing, 'columns')
  const derivedRows = rows ?? solveAxis(height, tileHeight, margin, spacing, 'rows')

  return { columns: derivedColumns, rows: derivedRows }
}

function solveAxis(totalSize, tileSize, margin, spacing, label) {
  const usable = totalSize - margin * 2 + spacing
  const step = tileSize + spacing
  if (usable <= 0 || usable % step !== 0) {
    throw new Error(`Could not derive ${label} from image size ${totalSize}. Check tile size, margin, and spacing.`)
  }

  const count = usable / step
  if (!Number.isInteger(count) || count <= 0) {
    throw new Error(`Derived ${label} must be a positive integer`)
  }

  return count
}

function createTemplateMetadata(options, dimensions, grid) {
  const totalTiles = grid.columns * grid.rows
  const tiles = []

  const groundFrames = pickFrames(totalTiles, 0, 2)
  const wallFrames = pickFrames(totalTiles, 2, 9)
  const decorFrames = pickFrames(totalTiles, 11, 8)

  for (let frame = 0; frame < totalTiles; frame++) {
    const x = frame % grid.columns
    const y = Math.floor(frame / grid.columns)
    const name = `tile-r${y}-c${x}`
    const tile = {
      frame,
      name,
      label: `Tile ${y},${x}`,
      type: 'unused',
      x,
      y,
    }

    if (groundFrames.includes(frame)) {
      tile.type = 'ground'
      tile.palette = true
    } else if (wallFrames.includes(frame)) {
      tile.type = 'wall'
      tile.palette = true
      tile.solid = true
    } else if (decorFrames.includes(frame)) {
      tile.type = 'decor'
      tile.palette = true
    }

    tiles.push(tile)
  }

  const defaults = {
    ground: groundFrames.map((frame) => tiles[frame].name),
    walls: wallFrames.map((frame) => tiles[frame].name),
    decor: decorFrames.map((frame) => tiles[frame].name),
    collision: tiles[wallFrames[0]].name,
    borderWalls: {
      topLeft: tiles[wallFrames[0]].name,
      top: tiles[wallFrames[1]].name,
      topRight: tiles[wallFrames[2]].name,
      left: tiles[wallFrames[3]].name,
      right: tiles[wallFrames[4]].name,
      bottomLeft: tiles[wallFrames[5]].name,
      bottom: tiles[wallFrames[6]].name,
      bottomRight: tiles[wallFrames[7]].name,
    },
  }

  return {
    name: options.name,
    textureKey: options.textureKey,
    image: path.basename(options.image),
    tileWidth: options.tileWidth,
    tileHeight: options.tileHeight,
    margin: options.margin,
    spacing: options.spacing,
    columns: grid.columns,
    rows: grid.rows,
    imageWidth: dimensions.width,
    imageHeight: dimensions.height,
    autoGenerated: true,
    notes: [
      'Review and rename tile entries after generation.',
      'Update defaults to match the intended ground, wall, decor, and collision tiles.',
    ],
    defaults,
    tiles,
  }
}

function pickFrames(totalTiles, start, count) {
  const frames = []
  for (let i = 0; i < count; i++) {
    frames.push(Math.min(start + i, totalTiles - 1))
  }
  return frames
}

function main() {
  const root = process.cwd()
  const options = parseArgs(process.argv.slice(2))
  const imagePath = path.resolve(root, options.image)
  const outputPath = path.resolve(root, options.output)
  const dimensions = readPngDimensions(imagePath)
  const grid = deriveGrid({
    width: dimensions.width,
    height: dimensions.height,
    tileWidth: options.tileWidth,
    tileHeight: options.tileHeight,
    margin: options.margin,
    spacing: options.spacing,
    columns: options.columns,
    rows: options.rows,
  })

  const metadata = createTemplateMetadata(options, dimensions, grid)
  fs.writeFileSync(outputPath, `${JSON.stringify(metadata, null, 2)}\n`, 'utf8')

  process.stdout.write([
    `Generated ${path.relative(root, outputPath)}`,
    `Image: ${path.relative(root, imagePath)} (${dimensions.width}x${dimensions.height})`,
    `Grid: ${grid.columns} columns x ${grid.rows} rows`,
    'Review the generated defaults and tile names before using it in-game.',
  ].join('\n'))
}

try {
  main()
} catch (error) {
  process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`)
  process.exitCode = 1
}
